DROP TABLE IF EXISTS SR_CANCEL_REQUESTS;
DROP TABLE IF EXISTS SR_PAYMENTS;
DROP TABLE IF EXISTS SR_RESERVATIONS;
DROP TABLE IF EXISTS SR_RESOURCES;
DROP TABLE IF EXISTS SR_USERS;

CREATE TABLE SR_USERS(
	USER_ID		VARCHAR(20)		PRIMARY KEY,
	PASSWORD	VARCHAR(30)		NOT NULL,
	NAME		VARCHAR(30)		NOT NULL,
	PHONE		VARCHAR(20),
	ROLE		VARCHAR(10)		NOT NULL,
	JOIN_DATE	TIMESTAMP		DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE SR_RESOURCES(
	RESOURCE_ID		BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	TYPE			VARCHAR(10)		NOT NULL,
	NAME			VARCHAR(50)		NOT NULL,
	LOCATION		VARCHAR(50)		NOT NULL,
	PRICE			INT				NOT NULL,
	STATUS			VARCHAR(20)		DEFAULT 'AVAILABLE',
	DISPLAY_ORDER	INT				NOT NULL
);

CREATE TABLE SR_RESERVATIONS(
	RESERVATION_ID	BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	USER_ID			VARCHAR(20)		NOT NULL,
	RESOURCE_ID		BIGINT			NOT NULL,
	START_TIME		TIMESTAMP		NOT NULL,
	END_TIME		TIMESTAMP		NOT NULL,
	STATUS			VARCHAR(20)		DEFAULT 'RESERVED',
	CREATED_AT		TIMESTAMP		DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY(USER_ID) REFERENCES SR_USERS(USER_ID),
	FOREIGN KEY(RESOURCE_ID) REFERENCES SR_RESOURCES(RESOURCE_ID)
);

CREATE TABLE SR_PAYMENTS(
	PAYMENT_ID		BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	RESERVATION_ID	BIGINT			NOT NULL,
	AMOUNT			INT				NOT NULL,
	METHOD			VARCHAR(20)		NOT NULL,
	PAYMENT_STATUS	VARCHAR(20)		NOT NULL,
	PAID_AT			TIMESTAMP		DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY(RESERVATION_ID) REFERENCES SR_RESERVATIONS(RESERVATION_ID)
);

CREATE TABLE SR_CANCEL_REQUESTS(
	REQUEST_ID		BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	RESERVATION_ID	BIGINT			NOT NULL,
	USER_ID			VARCHAR(20)		NOT NULL,
	REQUEST_STATUS	VARCHAR(20)		NOT NULL,
	REASON			VARCHAR(200),
	REQUESTED_AT	TIMESTAMP		DEFAULT CURRENT_TIMESTAMP,
	PROCESSED_AT	TIMESTAMP,
	FOREIGN KEY(RESERVATION_ID) REFERENCES SR_RESERVATIONS(RESERVATION_ID),
	FOREIGN KEY(USER_ID) REFERENCES SR_USERS(USER_ID)
);
